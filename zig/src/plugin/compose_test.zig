test "pathInputsToRepin: safety filter drops anything but user / p-<valid name>" {
	try expectRepin(
		\\{"nodes":{
		\\ "n":{"original":{"path":"/x","type":"path"}},
		\\ "root":{"inputs":{"--option":"n","p-":"n","p-Bad!":"n","p--x":"n","p-1abc":"n","nixpkgs":"n","p-ok":"n"}}},
		\\ "root":"root","version":7}
