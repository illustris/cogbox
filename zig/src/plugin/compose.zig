// Render and write the generated composition flake that folds every plugin's
// cogboxPlugins.<attr>.module (plus the per-instance user flake) into one module.
//
// The file is a pure function of config.json's .plugins array plus the
// on-disk plugin sources, and is regenerated on every plugin mutation;
// cogbox-launch.sh points --override-input userExtensions at its directory
// when plugins exist.
//
// Each plugin input resolves OFFLINE at launch: when the plugin's source has
// been materialized on the persistent PVC (has_source), the input is a `path:`
// ref read straight from disk (no fetcher, so no network and no credential
// needed at launch -- which is the whole point: launch has no token). A
// `git+http(s)` input pinned by ?ref=&rev= cannot be made offline (nix's git
// fetcher re-contacts the remote to verify the rev on a fresh store), so the
// locked git URL is only a migration fallback for a plugin added before the
// source was materialized.

const std = @import("std");
const name_mod = @import("name.zig");

pub const PluginRef = struct {
	name: []const u8,
	locked_url: []const u8,
	attr: []const u8 = "default", // nixosModules attr to import
	// Whether this plugin's source has been materialized under
	// <sources_dir>/<name>; when true, render emits a `path:` input (offline)
	// instead of the locked git/tarball URL. Set by the caller from a
	// filesystem check, so render stays a pure function of config + disk.
	has_source: bool = false,
	// The flake's subdir (`?dir=` query param) when the plugin lives in a
	// subdir of its repo. The materialized source is the repo ROOT, so the
	// path: input must carry `?dir=<dir>` to locate the flake. null = repo root.
	dir: ?[]const u8 = null,
};

pub const RenderError = error{
	NoPlugins,
	OutOfMemory,
};

/// Render the composition flake. Plugin inputs are named "p-<name>" (quoted
/// attrs) so they can never collide with `user`/`self`; the user flake is
/// always imported, last. `sources_dir` is the absolute base dir under which
/// each materialized plugin source lives (<sources_dir>/<name>); a plugin with
/// has_source=true points its input there as `path:` (offline at launch),
/// otherwise it falls back to the locked git/tarball URL (migration path).
pub fn render(
	allocator: std.mem.Allocator,
	instance: []const u8,
	user_flake_dir: []const u8,
	sources_dir: []const u8,
	plugins: []const PluginRef,
) RenderError![]u8 {
	if (plugins.len == 0) return error.NoPlugins;

	var out: std.ArrayList(u8) = .empty;
	defer out.deinit(allocator);

	try out.appendSlice(allocator, "# GENERATED by 'cogbox plugin' -- DO NOT EDIT.\n" ++
		"# Regenerated from config.json (.plugins) on every plugin add/del/update.\n" ++
		"{\n" ++
		"\tdescription = \"cogbox plugin composition for instance '");
	try out.appendSlice(allocator, instance);
	try out.appendSlice(allocator, "'\";\n\n\tinputs = {\n\t\tuser.url = \"path:");
	try appendNixString(allocator, &out, user_flake_dir);
	try out.appendSlice(allocator, "\";\n");
	for (plugins) |p| {
		try out.appendSlice(allocator, "\t\t\"p-");
		try out.appendSlice(allocator, p.name);
		try out.appendSlice(allocator, "\".url = \"");
		if (p.has_source) {
			// Offline at launch: read the materialized source from disk. For a
			// subdir flake (`?dir=`) the materialized tree is the repo root, so
			// carry the same dir param to locate the flake within it.
			try out.appendSlice(allocator, "path:");
			try appendNixString(allocator, &out, sources_dir);
			try out.append(allocator, '/');
			try appendNixString(allocator, &out, p.name);
			if (p.dir) |d| {
				try out.appendSlice(allocator, "?dir=");
				try appendNixString(allocator, &out, d);
			}
		} else {
			// Not yet hydrated (added before source materialization): fall
			// back to the locked URL. A git+ URL still needs the network at
			// launch -- the path: rewrite above is the actual offline fix.
			try appendNixString(allocator, &out, p.locked_url);
		}
		try out.appendSlice(allocator, "\";\n");
	}
	try out.appendSlice(allocator, "\t};\n\n" ++
		"\toutputs = { self, user, ... }@inputs: {\n" ++
		"\t\tnixosModules.default = {\n" ++
		"\t\t\timports = [\n");
	for (plugins) |p| {
		// Import the plugin's module via its cogboxPlugins.<attr>.module
		// reference; `or {}` makes the module optional (a pure-policy plugin
		// that only contributes networkRules/l7Rules/inject omits it).
		//
		// The `_file` wrapper carries PROVENANCE into the module system. The
		// merged config.cogbox the guest brain reads is anonymous -- every
		// contents root is just some /nix/store/...-source path, which is why
		// a cross-plugin skill-name collision used to fail the build naming no
		// plugin. nixpkgs passes a module's `_file` down as the fallback file
		// for each inline module it imports (lib/modules.nix: loadModule hands
		// the parent's _file to unifyModuleSyntax, which takes
		// `_file = toString m._file or file`), and a plugin's module is a bare
		// FUNCTION out of a flake output carrying no _file of its own -- so it
		// inherits "p-<name>" from this wrapper, all the way down to the
		// option definition. flake.nix then reads
		// options.cogbox.contents.definitionsWithLocations to learn which
		// plugin contributed which root, and qualifies colliding unit names as
		// "<plugin>-<unit>" instead of refusing to build. The user flake gets
		// the "cogbox-user" marker so the brain can leave the instance's OWN
		// content unqualified.
		try out.appendSlice(allocator, "\t\t\t\t{ _file = \"p-");
		try appendNixString(allocator, &out, p.name);
		try out.appendSlice(allocator, "\"; imports = [ (inputs.\"p-");
		try out.appendSlice(allocator, p.name);
		try out.appendSlice(allocator, "\".cogboxPlugins.\"");
		try out.appendSlice(allocator, p.attr);
		try out.appendSlice(allocator, "\".module or {}) ]; }\n");
	}
	try out.appendSlice(allocator, "\t\t\t\t{ _file = \"cogbox-user\"; imports = [ user.nixosModules.default ]; }\n" ++
		"\t\t\t];\n" ++
		"\t\t};\n" ++
		"\t};\n" ++
		"}\n");

	return try out.toOwnedSlice(allocator);
}

/// Escape for a double-quoted nix string: `\`, `"`, and `${`.
fn appendNixString(allocator: std.mem.Allocator, out: *std.ArrayList(u8), s: []const u8) !void {
	for (s, 0..) |c, i| {
		switch (c) {
			'\\' => try out.appendSlice(allocator, "\\\\"),
			'"' => try out.appendSlice(allocator, "\\\""),
			'$' => {
				if (i + 1 < s.len and s[i + 1] == '{') {
					try out.appendSlice(allocator, "\\$");
				} else {
					try out.append(allocator, c);
				}
			},
			else => try out.append(allocator, c),
		}
	}
}

/// Atomically write `rendered` as <dir>/flake.nix (mkdir -p, .tmp + rename).
/// An existing flake.lock is KEPT (not deleted): the caller reconciles it with
/// `nix flake lock` plus a re-pin of every path: input (pathInputsToRepin +
/// nix.flakeUpdateInputs) after this write, so launch resolves from a coherent,
/// already-pinned lock instead of re-resolving every input (which a fresh-store
/// launch can't do offline for a git+ input), while a path: input whose
/// on-disk content changed still gets its new narHash. The lock is dropped only
/// when the last plugin is removed (removeCompositionFlake).
pub fn writeCompositionFlake(
	allocator: std.mem.Allocator,
	io: std.Io,
	dir: []const u8,
	rendered: []const u8,
) !void {
	const cwd = std.Io.Dir.cwd();
	try cwd.createDirPath(io, dir);

	const path = try std.fs.path.join(allocator, &.{ dir, "flake.nix" });
	defer allocator.free(path);
	var nonce: [16]u8 = undefined;
	io.random(&nonce);
	const tmp_path = try std.fmt.allocPrint(allocator, "{s}.{x}.tmp", .{ path, nonce });
	defer allocator.free(tmp_path);
	defer cwd.deleteFile(io, tmp_path) catch {};

	{
		const f = try cwd.createFile(io, tmp_path, .{ .exclusive = true });
		defer f.close(io);
		var write_buf: [4096]u8 = undefined;
		var writer = f.writer(io, &write_buf);
		try writer.interface.writeAll(rendered);
		try writer.flush();
		try f.sync(io);
	}
	try cwd.rename(tmp_path, cwd, path, io);
}

/// Remove the generated flake (used when the last plugin is deleted, so the
/// launcher falls back to the plain per-instance flake path).
pub fn removeCompositionFlake(allocator: std.mem.Allocator, io: std.Io, dir: []const u8) !void {
	const cwd = std.Io.Dir.cwd();
	for ([_][]const u8{ "flake.nix", "flake.nix.tmp", "flake.lock" }) |f| {
		const path = try std.fs.path.join(allocator, &.{ dir, f });
		defer allocator.free(path);
		cwd.deleteFile(io, path) catch {};
	}
}

/// The composition inputs to re-pin with `nix flake update`: every root input
/// of the composition `lock_json` (a flake.lock) whose node's `original.type`
/// is "path" (materialized plugin sources and the `user` flake). Plain
/// `nix flake lock` keeps a path: input's old narHash even when its content
/// changed, so these are the inputs that need an explicit re-pin; git+/tarball
/// fallback inputs are skipped (re-resolving them needs the network).
///
/// Returns the input NAMES (the keys under nodes.root.inputs), not the node
/// keys, which nix may suffix (`p-foo_2`). SAFETY FILTER: the lock lives on a
/// sandbox-writable volume and the names become nix argv run with the acting
/// user's fetch credentials, so only "user" and "p-<valid plugin name>" are
/// accepted; anything else (including a name starting with '-') is silently
/// dropped. A malformed/unexpected shape yields an empty list (only OOM is an
/// error). Caller frees with freeInputNames.
pub fn pathInputsToRepin(allocator: std.mem.Allocator, lock_json: []const u8) error{OutOfMemory}![][]const u8 {
	var names: std.ArrayList([]const u8) = .empty;
	errdefer {
		for (names.items) |n| allocator.free(n);
		names.deinit(allocator);
	}

	const parsed = std.json.parseFromSlice(std.json.Value, allocator, lock_json, .{}) catch |err| switch (err) {
		error.OutOfMemory => return error.OutOfMemory,
		else => return names.toOwnedSlice(allocator),
	};
	defer parsed.deinit();

	collect: {
		if (parsed.value != .object) break :collect;
		const nodes = parsed.value.object.get("nodes") orelse break :collect;
		if (nodes != .object) break :collect;
		const root = nodes.object.get("root") orelse break :collect;
		if (root != .object) break :collect;
		const inputs = root.object.get("inputs") orelse break :collect;
		if (inputs != .object) break :collect;

		var it = inputs.object.iterator();
		while (it.next()) |entry| {
			const input_name = entry.key_ptr.*;
			const node_key = entry.value_ptr.*;
			// A `follows` input is an array path, not a node key: skip it.
			if (node_key != .string) continue;
			if (!isRepinnableName(input_name)) continue;
			const node = nodes.object.get(node_key.string) orelse continue;
			if (node != .object) continue;
			const original = node.object.get("original") orelse continue;
			if (original != .object) continue;
			const ty = original.object.get("type") orelse continue;
			if (ty != .string or !std.mem.eql(u8, ty.string, "path")) continue;
			const dup = try allocator.dupe(u8, input_name);
			errdefer allocator.free(dup);
			try names.append(allocator, dup);
		}
	}
	return names.toOwnedSlice(allocator);
}

/// Free a list returned by pathInputsToRepin.
pub fn freeInputNames(allocator: std.mem.Allocator, names: [][]const u8) void {
	for (names) |n| allocator.free(n);
	allocator.free(names);
}

/// The pathInputsToRepin safety filter: exactly "user", or "p-" followed by a
/// valid plugin name (the only input names render ever emits).
fn isRepinnableName(n: []const u8) bool {
	if (std.mem.eql(u8, n, "user")) return true;
	if (!std.mem.startsWith(u8, n, "p-")) return false;
	return name_mod.isValidPluginName(n[2..]);
}

/// The `locked.narHash` of root input `input_name`'s node in the composition
/// `lock_json`, or null when the lock is malformed, the input is absent, is a
/// `follows`, or carries no narHash. Caller frees. Only OOM is an error.
pub fn lockedNarHash(allocator: std.mem.Allocator, lock_json: []const u8, input_name: []const u8) error{OutOfMemory}!?[]u8 {
	const parsed = std.json.parseFromSlice(std.json.Value, allocator, lock_json, .{}) catch |err| switch (err) {
		error.OutOfMemory => return error.OutOfMemory,
		else => return null,
	};
	defer parsed.deinit();
	if (parsed.value != .object) return null;
	const nodes = parsed.value.object.get("nodes") orelse return null;
	if (nodes != .object) return null;
	const root = nodes.object.get("root") orelse return null;
	if (root != .object) return null;
	const inputs = root.object.get("inputs") orelse return null;
	if (inputs != .object) return null;
	const node_key = inputs.object.get(input_name) orelse return null;
	if (node_key != .string) return null;
	const node = nodes.object.get(node_key.string) orelse return null;
	if (node != .object) return null;
	const locked = node.object.get("locked") orelse return null;
	if (locked != .object) return null;
	const nh = locked.object.get("narHash") orelse return null;
	if (nh != .string) return null;
	return try allocator.dupe(u8, nh.string);
}

/// What to do with one path: input candidate (pathInputsToRepin) before any
/// `nix flake update` runs. The re-pin must never be blind: an update-all of
/// the path: inputs would pin whatever sits on disk, including a half-copied
/// plugin-sources tree or one a killed op left at a rev config.json never
/// recorded, and it would float an input's transitive inputs even when the
/// input itself is current.
pub const RepinVerdict = enum {
	/// locked narHash == on-disk hash: leave the input alone.
	current,
	/// stale, and the on-disk tree is the recorded pin (or it is `user`,
	/// which has no recorded pin): re-pin it.
	repin,
	/// stale, but the on-disk plugin tree is NOT what config.json records
	/// (partial copy, interrupted update, missing narHash): keep the old pin.
	disagrees_with_record,
	/// the on-disk tree could not be hashed: keep the old pin.
	unverifiable,
};

/// Pure decision for one candidate. `locked` is the lock's narHash for the
/// input (lockedNarHash), `disk` the `nix hash path` of its source root,
/// `recorded` config.json's .plugins[].narHash for a `p-<name>` input (ignored
/// for `user`, which config.json does not pin).
pub fn repinVerdict(input_name: []const u8, locked: ?[]const u8, disk: ?[]const u8, recorded: ?[]const u8) RepinVerdict {
	const d = disk orelse return .unverifiable;
	if (locked) |l| {
		if (std.mem.eql(u8, l, d)) return .current;
	}
	if (std.mem.eql(u8, input_name, "user")) return .repin;
	const r = recorded orelse return .disagrees_with_record;
	return if (std.mem.eql(u8, r, d)) .repin else .disagrees_with_record;
}
